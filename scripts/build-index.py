#!/usr/bin/env python3
"""Regenerate INDEX.md from the YAML frontmatter of every markdown doc.

Usage: python3 scripts/build-index.py [--check]
--check exits 1 if INDEX.md would change (for CI / scheduled tasks).
Only depends on the standard library so it runs anywhere.
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCAN = ["WORKFLOW.md", "docs"]
FM = re.compile(r"^---\n(.*?)\n---", re.S)

def parse_frontmatter(text):
    m = FM.match(text)
    if not m:
        return None
    out = {}
    for line in m.group(1).splitlines():
        if ":" not in line or line.startswith(" "):
            continue
        k, v = line.split(":", 1)
        v = v.split("#", 1)[0].strip()
        if v.startswith("[") and v.endswith("]"):
            v = [x.strip().strip("'\"") for x in v[1:-1].split(",") if x.strip()]
        elif v in ("null", "~", ""):
            v = None
        out[k.strip()] = v
    return out

def docs():
    paths = []
    for s in SCAN:
        p = ROOT / s
        paths += [p] if p.is_file() else sorted(p.rglob("*.md"))
    for p in paths:
        if p.name in ("README.md",):
            continue
        fm = parse_frontmatter(p.read_text(encoding="utf-8"))
        if fm and fm.get("id"):
            yield p.relative_to(ROOT).as_posix(), fm

def render():
    rows = list(docs())
    by_type = {}
    for path, fm in rows:
        by_type.setdefault(fm.get("type", "other"), []).append((path, fm))
    lines = ["# Index", "", "_Generated by `scripts/build-index.py`. Do not edit by hand._", ""]
    counts = {}
    for _, fm in rows:
        counts[fm.get("status", "?")] = counts.get(fm.get("status", "?"), 0) + 1
    lines.append("**Status counts:** " + ", ".join(f"{k}: {v}" for k, v in sorted(counts.items())))
    lines.append("")
    for t in sorted(by_type):
        lines += [f"## {t}", "", "| id | title | status | updated | depends_on | path |", "|---|---|---|---|---|---|"]
        for path, fm in by_type[t]:
            dep = ", ".join(fm.get("depends_on") or []) if isinstance(fm.get("depends_on"), list) else (fm.get("depends_on") or "")
            lines.append(f"| {fm['id']} | {fm.get('title') or ''} | {fm.get('status','')} | {fm.get('updated','')} | {dep} | [{path}]({path}) |")
        lines.append("")
    # gaps
    stuck = [fm["id"] for _, fm in rows if fm.get("status") == "review"]
    lines += ["## Gaps", ""]
    lines += [f"- in review: `{s}`" for s in stuck] or ["- none"]
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    new = render()
    target = ROOT / "INDEX.md"
    old = target.read_text(encoding="utf-8") if target.exists() else ""
    if "--check" in sys.argv:
        sys.exit(0 if old == new else 1)
    target.write_text(new, encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")
